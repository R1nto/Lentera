/** Canonical indicator catalog shared by the teacher's choices and report publication. */
export type ReportIndicator = { id: string; code: string; description: string; criteria: string | null };

const recordOf = (value: unknown): Record<string, unknown> | null =>
  value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : null;
const rowsOf = (value: unknown): unknown[] => Array.isArray(value) ? value : [];
const asText = (value: unknown): string => typeof value === 'string' ? value.trim() : '';

/**
 * A snapshot may prepend an indicator code (e.g. "IND-01: ...") to the text,
 * whereas the source module keeps it in a separate field. Both mean the same
 * indicator. Do not treat differently formatted IDs as different objectives.
 */
export function normalizedIndicatorDescription(value: unknown): string {
  return asText(value)
    .replace(/^\s*(?:IND(?:IKATOR)?)[-_\s]*\d+(?:[-_.]\d+)*\s*[:.\-–]\s*/i, '')
    .normalize('NFKC')
    .toLocaleLowerCase('id-ID')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

/** Accept either the AI's source JSON or an existing session TP snapshot. */
function fromModule(root: unknown): ReportIndicator[] {
  const data = recordOf(root);
  const rows = rowsOf(data?.learningObjectives ?? data?.learning_objectives ?? data?.tp);
  return rows.flatMap((tp, ti) => {
    const item = recordOf(tp);
    const indicatorRows = rowsOf(item?.indicators ?? item?.learningIndicators ?? item?.learning_indicators);
    return indicatorRows.flatMap((raw, ii) => {
      const indicator = recordOf(raw);
      const rawDescription = asText(indicator?.description ?? (typeof raw === 'string' ? raw : ''));
      const normalized = normalizedIndicatorDescription(rawDescription);
      if (!normalized) return [];
      const rawCode = asText(indicator?.code) || asText(indicator?.id);
      const codeFromText = rawDescription.match(/^\s*(IND(?:IKATOR)?[-_\s]*\d+(?:[-_.]\d+)*)\s*[:.\-–]/i)?.[1];
      const code = rawCode || codeFromText || `IND-${ti + 1}-${ii + 1}`;
      const description = rawDescription.replace(/^\s*IND(?:IKATOR)?[-_\s]*\d+(?:[-_.]\d+)*\s*[:.\-–]\s*/i, '').trim();
      return [{ id: `module-${ti}-${ii}`, code, description,
        criteria: asText(indicator?.criteria) || null }];
    });
  });
}

export function collectReportIndicators(
  curriculumIndicators: ReportIndicator[], snapshot: unknown, moduleContent: unknown,
): ReportIndicator[] {
  // The original module is authoritative for codes/wording; the snapshot may
  // contain older autogenerated codes for these exact same descriptions.
  const original = fromModule(moduleContent);
  const snapshotRows = fromModule(snapshot);
  if (!original.length && !snapshotRows.length) {
    // Curriculum-backed sessions still use their real UUID indicator IDs.
    return uniqueByDescription(curriculumIndicators);
  }
  return uniqueByDescription([...original, ...snapshotRows]);
}

function uniqueByDescription(rows: ReportIndicator[]): ReportIndicator[] {
  const seen = new Set<string>();
  const unique: ReportIndicator[] = [];
  for (const indicator of rows) {
    const normalized = normalizedIndicatorDescription(indicator.description);
    const key = normalized || `code:${indicator.code.toLocaleLowerCase('id-ID')}`;
    if (seen.has(key)) continue;
    seen.add(key);
    unique.push(indicator);
  }
  // Keep the original module order, not alphabetical/generated-code order.
  // Stable IDs are reassigned AFTER de-duplication so both endpoints agree.
  return unique.map((item, index) => item.id.startsWith('module-')
    ? { ...item, id: `module-${index}` } : item);
}
